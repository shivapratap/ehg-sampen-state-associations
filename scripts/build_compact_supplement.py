def env(text, marker, nth=0):
    """Return the longtable environment (verbatim) that follows `marker`."""
    i = text.index(marker)
    for _ in range(nth + 1):
        s = text.index("\\begin{longtable}", i)
        i = s + 1
    e = text.index("\\end{longtable}", s) + len("\\end{longtable}")
    return text[s:e]


def rows(envtext):
    """Data rows (list of cell lists) of a longtable, after \\endhead and before \\bottomrule."""
    body = envtext.split("\\endhead", 1)[1].split("\\bottomrule", 1)[0]
    out = []
    for ln in body.strip().split("\n"):
        ln = ln.strip()
        if not ln.endswith("\\\\") or ln.startswith("\\midrule"):
            continue
        out.append([c.strip() for c in ln[:-2].split(" & ")])
    return out


def num(cell):
    c = re.sub(r"\\textbf\{([^}]*)\}", r"\1", cell).replace("$-$", "-").replace("$", "")
    return float(c)


